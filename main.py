import os
import sys
import json
import urllib.request

from google.oauth2.credentials import Credentials
from googleapiclient.discovery import build
from googleapiclient.http import MediaFileUpload


LANG = (os.environ.get("VIDEO_LANG") or "en").lower()   # "en", "hi" or "hinglish"
# Script files are played in order. Override with SCRIPTS_FILE="a.json,b.json" in daily.yml.
SCRIPTS_FILE = (os.environ.get("SCRIPTS_FILE")
                or {"hi": "scripts_hi.json", "hinglish": "scripts_hinglish.json"}.get(LANG, "scripts.json"))
NICHE = os.environ.get("NICHE") or "study tips and productivity tips for students"
PRIVACY = "public"  # "public", "unlisted" or "private"
GEMINI_MODELS = ["gemini-2.5-flash", "gemini-3.1-flash-lite", "gemini-2.5-flash-lite"]


def load_state():
    s = {}
    if os.path.exists("state.json"):
        with open("state.json") as f:
            s = json.load(f)
    s.setdefault("script_index", 0)
    s.setdefault("count", 0)
    s.setdefault("recent", [])
    return s


def save_state(state):
    with open("state.json", "w") as f:
        json.dump(state, f, indent=1)


def get_youtube():
    creds = Credentials(
        None,
        refresh_token=os.environ["REFRESH_TOKEN"],
        client_id=os.environ["CLIENT_ID"],
        client_secret=os.environ["CLIENT_SECRET"],
        token_uri="https://oauth2.googleapis.com/token",
    )
    return build("youtube", "v3", credentials=creds)


def gemini_script(recent):
    """Optional: ask Gemini for a new script when scripts.json runs out."""
    key = os.environ.get("GEMINI_API_KEY")
    if not key:
        return None
    language = {"hi": "Hindi (Devanagari script)",
                "hinglish": "Hinglish (Hindi written in English/Roman letters, as people speak in India)"}.get(LANG, "English")
    prompt = (
        f"Write a script for a 40-second YouTube Short about {NICHE}. "
        f"Write the title, description and narration in {language}. "
        "Give practical, well-established advice only; no made-up statistics. "
        "Reply as JSON: {\"title\": \"max 60 chars\", \"description\": \"1-2 sentences\", "
        "\"scenes\": [{\"text\": \"about 16 words of narration\"}]} with exactly 6 scenes, "
        "a strong hook in scene 1 and a call to follow in scene 6. "
        f"Do not repeat these titles: {recent}."
    )
    payload = {"contents": [{"parts": [{"text": prompt}]}],
               "generationConfig": {"responseMimeType": "application/json"}}
    for model in GEMINI_MODELS:
        try:
            url = f"https://generativelanguage.googleapis.com/v1beta/models/{model}:generateContent"
            req = urllib.request.Request(
                url, data=json.dumps(payload).encode(),
                headers={"Content-Type": "application/json", "x-goog-api-key": key})
            with urllib.request.urlopen(req, timeout=120) as r:
                data = json.load(r)
            out = json.loads(data["candidates"][0]["content"]["parts"][0]["text"])
            assert out["title"] and len(out["scenes"]) >= 3
            assert all(s["text"] for s in out["scenes"])
            print("Script generated by", model)
            return out
        except Exception as e:
            print(f"Gemini model {model} failed: {e}")
    return None


def main():
    state = load_state()
    scripts = []
    for name in SCRIPTS_FILE.split(","):
        with open(name.strip(), encoding="utf-8") as f:
            scripts += json.load(f)

    if state["script_index"] < len(scripts):
        script = scripts[state["script_index"]]
        from_file = True
    else:
        script = gemini_script(state["recent"][-15:])
        from_file = False
        if script is None:
            print("OUT OF SCRIPTS: add more entries to scripts.json "
                  "(or fix GEMINI_API_KEY for automatic scripts).")
            sys.exit(1)

    credits = build_video(script, "clip.mp4")

    title = f"{script['title']} #Shorts"[:100]
    hashtags = script.get("hashtags") or ("#shorts #studytips" + (" #hindi" if LANG in ("hi", "hinglish") else ""))
    description = f"{script.get('description', script['title'])}\n\nOriginal code-drawn storyboard visuals.\n\n{hashtags}"

    yt = get_youtube()
    body = {
        "snippet": {
            "title": title,
            "description": description[:4900],
            "tags": script.get("tags", ["study tips", "productivity", "students", "shorts"]),
            "categoryId": str(script.get("category", "27")),  # 27 Education, 19 Travel, 2 Autos, 24 Entertainment
        },
        "status": {"privacyStatus": PRIVACY, "selfDeclaredMadeForKids": False},
    }
    media = MediaFileUpload("clip.mp4", chunksize=-1, resumable=True)
    res = yt.videos().insert(part="snippet,status", body=body, media_body=media).execute()
    print("Uploaded video id:", res["id"], "| title:", title)

    if from_file:
        state["script_index"] += 1
    state["count"] += 1
    state["recent"] = (state["recent"] + [script["title"]])[-30:]
    save_state(state)


if __name__ == "__main__":
    main()
